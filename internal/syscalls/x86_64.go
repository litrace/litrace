var (
	idToName = make(map[int64]string, len(entries))
	nameToID = make(map[string]int64, len(entries))
)

func init() {
	for _, entry := range entries {
		idToName[entry.ID] = entry.Name
		nameToID[entry.Name] = entry.ID
	}
}

func Name(id int64) string {
	if name, ok := idToName[id]; ok {
		return name
	}
	return fmt.Sprintf("syscall_0x%x", id)
}

func ID(name string) (int64, bool) {
	id, ok := nameToID[name]
	return id, ok
}

func Entries() []Entry {
	return entries
}
